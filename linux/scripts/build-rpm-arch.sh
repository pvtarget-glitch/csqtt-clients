#!/usr/bin/env bash
# Пакеты для Fedora/openSUSE (.rpm) и Arch (.pkg.tar.zst) из готового .deb:
# те же бинарники (собраны на Ubuntu 22.04, glibc 2.35), другие пути и
# сценарии установки. Пользователи — через systemd-sysusers.
#
#   scripts/build-rpm-arch.sh dist/csqtt-linux_<версия>+core<ядро>_amd64.deb
#
# Нужны dpkg-deb, rpmbuild (пакет rpm), bsdtar (libarchive-tools) и zstd.
set -euo pipefail

ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
DEB="$(readlink -f "${1:?укажи .deb}")"
DIST="$ROOT/dist"
cd "$ROOT"

for tool in dpkg-deb rpmbuild bsdtar zstd; do
  command -v "$tool" >/dev/null || { echo "нужен $tool" >&2; exit 1; }
done

FULL_VERSION="$(dpkg-deb -f "$DEB" Version)"          # 0.13.0+core2.5.0+linux.5
VERSION="${FULL_VERSION%%+*}"
CORE_VERSION="${FULL_VERSION#*+core}"
case "$(dpkg-deb -f "$DEB" Architecture)" in
  amd64) RPM_ARCH=x86_64; PAC_ARCH=x86_64 ;;
  arm64) RPM_ARCH=aarch64; PAC_ARCH=aarch64 ;;
  *) echo "неизвестная архитектура" >&2; exit 1 ;;
esac

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
TREE="$WORK/tree"
dpkg-deb -x "$DEB" "$TREE"

# В Arch и Fedora 42+ /usr/sbin — ссылка на /usr/bin: файлы только в /usr/bin.
mv "$TREE/usr/sbin/csqttd" "$TREE/usr/bin/csqttd"
rmdir "$TREE/usr/sbin"
sed -i 's#/usr/sbin/csqttd#/usr/bin/csqttd#g' "$TREE/usr/lib/systemd/system/csqttd.service"
mv "$TREE/usr/share/doc/csqtt-linux" "$TREE/usr/share/doc/csqtt"
install -D -m 644 packaging/csqtt.sysusers "$TREE/usr/lib/sysusers.d/csqtt.conf"

# --- rpm ---------------------------------------------------------------------
TOPDIR="$WORK/rpmbuild"
mkdir -p "$TOPDIR"/{SPECS,RPMS,BUILD,BUILDROOT}
sed -e "s#@VERSION@#$VERSION#g" -e "s#@ARCH@#$RPM_ARCH#g" \
    -e "s#@CORE_VERSION@#$CORE_VERSION#g" -e "s#@TREE@#$TREE#g" \
    packaging/rpm/csqtt.spec.in > "$TOPDIR/SPECS/csqtt.spec"
rpmbuild --quiet --define "_topdir $TOPDIR" --target "$RPM_ARCH" \
  --define "_binary_payload w19.zstdio" -bb "$TOPDIR/SPECS/csqtt.spec"
RPM="$(find "$TOPDIR/RPMS" -name '*.rpm' | head -1)"
cp "$RPM" "$DIST/csqtt-$VERSION-1.$RPM_ARCH.rpm"
echo "rpm: $DIST/csqtt-$VERSION-1.$RPM_ARCH.rpm"

# --- Arch --------------------------------------------------------------------
PKG="$WORK/arch"
cp -a "$TREE" "$PKG"
cp packaging/arch/csqtt.install "$PKG/.INSTALL"
SIZE="$(du -sb "$TREE" | cut -f1)"
cat > "$PKG/.PKGINFO" <<PKGINFO
# Generated by csqtt-clients scripts/build-rpm-arch.sh
pkgname = csqtt
pkgbase = csqtt
pkgver = $VERSION-1
pkgdesc = Linux client for the csqtt tunnel (core $CORE_VERSION)
url = https://github.com/pvtarget-glitch/csqtt-clients
builddate = $(date +%s)
packager = csqtt-clients CI
size = $SIZE
arch = $PAC_ARCH
license = LicenseRef-PolyForm-Noncommercial-1.0.0
backup = etc/csqtt/csqttd.toml
depend = glibc
depend = gcc-libs
depend = iproute2
depend = gtk3
depend = webkit2gtk-4.1
depend = python-gobject
optdepend = libayatana-appindicator: значок в трее
optdepend = nftables: программы мимо туннеля (csqtt direct)
optdepend = curl: обновления из окна и csqtt update
optdepend = polkit: установка обновлений из окна
optdepend = libnotify: уведомления
PKGINFO
(
  cd "$PKG"
  LANG=C bsdtar --uid 0 --gid 0 --uname root --gname root -czf .MTREE --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' \
    .PKGINFO .INSTALL usr etc
  LANG=C bsdtar --uid 0 --gid 0 --uname root --gname root -cf - .PKGINFO .INSTALL .MTREE usr etc \
    | zstd -q -c -T0 -19 > "$DIST/csqtt-$VERSION-1-$PAC_ARCH.pkg.tar.zst"
)
echo "arch: $DIST/csqtt-$VERSION-1-$PAC_ARCH.pkg.tar.zst"
